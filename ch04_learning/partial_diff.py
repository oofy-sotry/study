import numpy as np
from numerical_diff import numerical_diff

# =============================================
# 편미분 (Partial Differentiation)
# 변수가 여러 개인 함수에서 하나의 변수에 대해서만 미분
# 나머지 변수는 상수로 고정
# =============================================

# 테스트 함수: f(x0, x1) = x0² + x1²
# 해석적 편미분: ∂f/∂x0 = 2x0,  ∂f/∂x1 = 2x1
def function_2(x):
    return x[0]**2 + x[1]**2

# =============================================
# x0에 대한 편미분 (x1 = 4.0 고정)
# x1을 상수 4.0으로 고정하고 x0만 변수로 두는 1변수 함수로 변환
# =============================================
def function_tmp1(x0):
    return x0**2 + 4.0**2   # x1=4.0 고정

print("=== x0에 대한 편미분 (x0=3, x1=4 고정) ===")
result_x0 = numerical_diff(function_tmp1, 3.0)
print("수치 편미분값:", result_x0)   # 기댓값: 2*3 = 6.0
print("=> 해석적 편미분값(6.0)과 거의 일치함")
print("==============================")

# =============================================
# x1에 대한 편미분 (x0 = 3.0 고정)
# x0를 상수 3.0으로 고정하고 x1만 변수로 두는 1변수 함수로 변환
# =============================================
def function_tmp2(x1):
    return 3.0**2 + x1**2   # x0=3.0 고정

print("=== x1에 대한 편미분 (x0=3 고정, x1=4) ===")
result_x1 = numerical_diff(function_tmp2, 4.0)
print("수치 편미분값:", result_x1)   # 기댓값: 2*4 = 8.0
print("=> 해석적 편미분값(8.0)과 거의 일치함")
print("==============================")

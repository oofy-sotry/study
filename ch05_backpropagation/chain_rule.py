import numpy as np

# =============================================
# 5.2 연쇄법칙 (Chain Rule)
# 합성 함수의 미분 = 각 함수의 미분의 곱
# ∂z/∂x = ∂z/∂t × ∂t/∂x
# =============================================

# =============================================
# 예시: z = (x + y)²
# 분해: t = x + y  (덧셈 노드)
#       z = t²     (제곱 노드)
# =============================================
x = 2.0
y = 3.0

# 순전파
t = x + y      # 덧셈 노드: t = 5.0
z = t ** 2     # 제곱 노드: z = 25.0

print("=== 순전파 ===")
print(f"x={x}, y={y}")
print(f"t = x + y = {t}")
print(f"z = t²    = {z}")
print()

# =============================================
# 역전파: 연쇄법칙 적용
# ∂z/∂x = ∂z/∂t × ∂t/∂x
# =============================================

# 출발값
dL_dz = 1.0            # ∂L/∂z = 1

# 제곱 노드 역전파: z = t²  =>  ∂z/∂t = 2t
dz_dt = 2 * t          # 2 × 5 = 10
dL_dt = dL_dz * dz_dt  # 1 × 10 = 10

# 덧셈 노드 역전파: t = x + y  =>  ∂t/∂x = 1, ∂t/∂y = 1
dt_dx = 1
dt_dy = 1
dL_dx = dL_dt * dt_dx  # 10 × 1 = 10
dL_dy = dL_dt * dt_dy  # 10 × 1 = 10

print("=== 역전파 (연쇄법칙) ===")
print(f"출발값 ∂L/∂z          = {dL_dz}")
print(f"제곱 노드: ∂z/∂t=2t   = {dz_dt}  →  ∂L/∂t = {dL_dt}")
print(f"덧셈 노드: ∂t/∂x=1    →  ∂L/∂x = {dL_dx}")
print(f"덧셈 노드: ∂t/∂y=1    →  ∂L/∂y = {dL_dy}")
print()
print(f"∂z/∂x = ∂z/∂t × ∂t/∂x = {dz_dt} × {dt_dx} = {dL_dx}")
print(f"  (해석적 미분: ∂(x+y)²/∂x = 2(x+y) = {2*(x+y)})")
print("==============================\n")

# =============================================
# 수치 미분으로 검증
# =============================================
def f(x, y):
    return (x + y) ** 2

h = 1e-4
numerical_dx = (f(x + h, y) - f(x - h, y)) / (2 * h)
numerical_dy = (f(x, y + h) - f(x, y - h)) / (2 * h)

print("=== 수치 미분으로 검증 ===")
print(f"∂z/∂x — 역전파: {dL_dx}, 수치 미분: {numerical_dx:.6f}, 오차: {abs(dL_dx - numerical_dx):.2e}")
print(f"∂z/∂y — 역전파: {dL_dy}, 수치 미분: {numerical_dy:.6f}, 오차: {abs(dL_dy - numerical_dy):.2e}")
print("=> 연쇄법칙(역전파)과 수치 미분 결과 일치")
print("==============================\n")

# =============================================
# 덧셈 노드의 특성: 기울기를 그대로 흘려보냄
# 곱셈 노드의 특성: 순전파 입력값을 서로 교환해서 곱함
# =============================================
print("=== 노드별 역전파 특성 ===")

# 덧셈 노드: z = a + b
a, b = 3.0, 5.0
z_add = a + b
upstream = 2.0   # 상류에서 온 기울기

dz_da = upstream * 1   # 덧셈: 상류 기울기 그대로 전달
dz_db = upstream * 1
print(f"[덧셈 노드] z = {a} + {b} = {z_add}")
print(f"  상류 기울기 {upstream} → ∂L/∂a={dz_da}, ∂L/∂b={dz_db}  (기울기 그대로 전달)")

# 곱셈 노드: z = a × b
z_mul = a * b
dz_da = upstream * b   # 곱셈: 상대방 값을 곱해서 전달
dz_db = upstream * a
print(f"[곱셈 노드] z = {a} × {b} = {z_mul}")
print(f"  상류 기울기 {upstream} → ∂L/∂a={dz_da}, ∂L/∂b={dz_db}  (입력값 서로 교환해서 곱함)")
print("==============================")
